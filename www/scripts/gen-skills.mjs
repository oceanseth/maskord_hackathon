// Inline convex/skills/<kind>/<phase>.md into convex/skills/_generated.ts so the
// Convex bundler (esbuild, no .md loader) can ship them. See convex/skills/README.md.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'convex', 'skills');
const out = {};
for (const kind of readdirSync(root).filter((d) => statSync(join(root, d)).isDirectory())) {
  out[kind] = {};
  for (const file of readdirSync(join(root, kind)).filter((f) => f.endsWith('.md')).sort()) {
    out[kind][file.replace(/\.md$/, '')] = readFileSync(join(root, kind, file), 'utf8');
  }
}
const body =
  `// Generated by scripts/gen-skills.mjs from convex/skills/**/*.md. Do not edit; edit the markdown.\n` +
  `export const SKILLS: Record<string, Record<string, string>> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(join(root, '_generated.ts'), body);
console.log(`skills: ${Object.entries(out).map(([k, v]) => `${k}(${Object.keys(v).join(',')})`).join(' ')}`);
